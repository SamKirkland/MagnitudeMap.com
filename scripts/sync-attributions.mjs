/**
 * Build src/data/attributions.ts from each model's license.json + catalog names.
 * Run after adding/updating models: npm run sync-attributions
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const modelsDir = join(root, 'public', 'models')
const groundsDir = join(root, 'public', 'grounds')
const outPath = join(root, 'src', 'data', 'attributions.ts')
const catalogPath = join(root, 'src', 'data', 'catalog.ts')

function requiresAttribution(license) {
  const l = (license || '').toLowerCase()
  if (!l) return false
  if (l.includes('cc0') || l.includes('public domain')) return false
  if (l.includes('cc-by') || l.includes('cc by') || l === 'by' || l.startsWith('by-'))
    return true
  if (l.includes('attribution')) return true
  if (l.includes('nasa')) return true
  if (l.includes('mit') || l.includes('apache') || l.includes('bsd')) return true
  return true
}

function catalogNames() {
  const src = readFileSync(catalogPath, 'utf8')
  const names = {}
  const re = /id:\s*'([^']+)'[\s\S]*?name:\s*'((?:\\'|[^'])*)'/g
  let m
  while ((m = re.exec(src))) {
    names[m[1]] = m[2].replace(/\\'/g, "'")
  }
  return names
}

function readLicenseDir(dirRoot, names) {
  if (!existsSync(dirRoot)) return []
  const entries = []
  for (const id of readdirSync(dirRoot)) {
    const dir = join(dirRoot, id)
    if (!statSync(dir).isDirectory()) continue
    const licPath = join(dir, 'license.json')
    if (!existsSync(licPath)) continue
    const text = readFileSync(licPath, 'utf8').replace(/^\uFEFF/, '')
    const raw = JSON.parse(text)
    const license = raw.license || 'Unknown'
    const author = raw.author || 'Unknown'
    const source = raw.source || ''
    const sourceAsset = raw.sourceAsset || raw.file || 'model.glb'
    const catalogName = names[id] || raw.sourceAsset || id
    const attribution =
      raw.attribution ||
      `${catalogName} — ${sourceAsset} by ${author} (${license})${source ? ` — ${source}` : ''}`

    entries.push({
      id,
      catalogName,
      author,
      license,
      licenseLabel: raw.licenseLabel || license,
      source,
      sourceAsset,
      attribution,
      requiresAttribution: requiresAttribution(license),
      notes: raw.notes || '',
    })
  }
  return entries
}

function loadLicenses() {
  const names = catalogNames()
  const entries = [
    ...readLicenseDir(modelsDir, names),
    ...readLicenseDir(groundsDir, names),
  ]
  entries.sort((a, b) => a.catalogName.localeCompare(b.catalogName))
  return entries
}

function main() {
  const entries = loadLicenses()
  const body = `/* Auto-generated by scripts/sync-attributions.mjs — do not edit by hand. */
export type ModelAttribution = {
  id: string
  catalogName: string
  author: string
  license: string
  licenseLabel: string
  source: string
  sourceAsset: string
  attribution: string
  requiresAttribution: boolean
  notes: string
}

export const MODEL_ATTRIBUTIONS: ModelAttribution[] = ${JSON.stringify(entries, null, 2)}

export const REQUIRED_ATTRIBUTIONS = MODEL_ATTRIBUTIONS.filter(
  (entry) => entry.requiresAttribution,
)

export function attributionFor(id: string): ModelAttribution | undefined {
  return MODEL_ATTRIBUTIONS.find((entry) => entry.id === id)
}
`
  writeFileSync(outPath, body)
  console.log(`Wrote ${entries.length} attributions → src/data/attributions.ts`)
  console.log(
    `Required credit: ${entries.filter((e) => e.requiresAttribution).map((e) => e.id).join(', ') || '(none)'}`,
  )
}

main()
